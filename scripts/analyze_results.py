"""Aggregate W&B runs into LaTeX tables and summary plots for the paper.

Pulls all runs matching project tags, computes mean ± std across seeds,
and writes:
    - results/table_main.tex   : main results table (methods × scenarios)
    - results/table_ablations.tex : ablation table for selected method
    - results/figure_forgetting_curves.pdf : per-method forgetting curves

Usage:
    python scripts/analyze_results.py --project doccl-aaai2027
    python scripts/analyze_results.py --project doccl-aaai2027 --filter "tag:cil_cord"
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

try:
    import wandb
except ImportError:
    wandb = None


# ─── W&B run pulling ───────────────────────────────────────────────────────────


def pull_runs(project: str, entity: str | None = None) -> pd.DataFrame:
    """Pull all runs from a W&B project. Returns one row per run with summary metrics."""
    if wandb is None:
        raise ImportError("Install wandb: pip install wandb")
    api = wandb.Api()
    project_path = f"{entity}/{project}" if entity else project
    runs = api.runs(project_path)

    rows = []
    for r in runs:
        cfg = r.config
        summary = r.summary._json_dict
        rows.append({
            "name": r.name,
            "id": r.id,
            "state": r.state,
            "method": cfg.get("method", {}).get("name", "?"),
            "scenario": cfg.get("scenario", {}).get("name", "?"),
            "model": cfg.get("model", {}).get("name", "?"),
            "seed": cfg.get("seed", -1),
            "AA": summary.get("final/AA"),
            "BWT": summary.get("final/BWT"),
            "AF": summary.get("final/AF"),
            "FWT": summary.get("final/FWT"),
        })
    return pd.DataFrame(rows)


# ─── Aggregation ──────────────────────────────────────────────────────────────


def aggregate(df: pd.DataFrame, metric: str = "AA") -> pd.DataFrame:
    """Mean ± std of metric across seeds, indexed by (scenario, method)."""
    df = df[df["state"] == "finished"].copy()
    df = df.dropna(subset=[metric])
    agg = df.groupby(["scenario", "method"])[metric].agg(["mean", "std", "count"]).reset_index()
    agg["mean_std"] = agg.apply(lambda r: f"{r['mean']:.2f}±{r['std']:.2f}", axis=1)
    return agg


# ─── LaTeX writers ────────────────────────────────────────────────────────────


METHOD_ORDER = [
    "naive", "joint",
    "ewc", "lwf",
    "er", "der_pp",
    "l2p", "dualprompt", "coda_prompt",
    "o_lora",
    "doccl",
]
METHOD_DISPLAY = {
    "naive": "Naive (FT)", "joint": "Joint (Oracle)",
    "ewc": "EWC", "lwf": "LwF",
    "er": "ER", "der_pp": "DER\\texttt{++}",
    "l2p": "L2P", "dualprompt": "DualPrompt", "coda_prompt": "CODA-Prompt",
    "o_lora": "O-LoRA",
    "doccl": "\\textbf{DocCL (Ours)}",
}
SCENARIO_DISPLAY = {
    "cil_cord": "CIL-CORD", "dil": "DIL", "mixed": "Mixed",
}


def write_main_table(df: pd.DataFrame, output: Path, metric: str = "AA") -> None:
    """Write LaTeX table: methods (rows) × scenarios (cols), AA mean±std."""
    df = df[df["state"] == "finished"].dropna(subset=[metric])
    pivot_mean = df.pivot_table(
        values=metric, index="method", columns="scenario", aggfunc="mean"
    )
    pivot_std = df.pivot_table(
        values=metric, index="method", columns="scenario", aggfunc="std"
    )
    pivot_n = df.pivot_table(
        values=metric, index="method", columns="scenario", aggfunc="count"
    )

    methods = [m for m in METHOD_ORDER if m in pivot_mean.index]
    scenarios = [s for s in SCENARIO_DISPLAY if s in pivot_mean.columns]

    lines = [
        "% Auto-generated by scripts/analyze_results.py",
        f"% Metric: {metric} (mean ± std across seeds)",
        "\\begin{tabular}{l" + "c" * len(scenarios) + "}",
        "\\toprule",
        "Method & " + " & ".join(SCENARIO_DISPLAY[s] for s in scenarios) + " \\\\",
        "\\midrule",
    ]
    for m in methods:
        cells = []
        for s in scenarios:
            mean = pivot_mean.loc[m, s] if (m, s) in zip(pivot_mean.index.repeat(len(scenarios)), list(scenarios)*len(pivot_mean.index)) else None
            if pd.isna(pivot_mean.loc[m, s]):
                cells.append("--")
            else:
                cells.append(f"{pivot_mean.loc[m, s]:.2f}\\;{{\\scriptsize $\\pm$ {pivot_std.loc[m, s]:.2f}}}")
        lines.append(f"{METHOD_DISPLAY.get(m, m)} & " + " & ".join(cells) + " \\\\")
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
    ])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    print(f"Wrote {output}")


def write_pivot_csv(df: pd.DataFrame, output: Path, metric: str = "AA") -> None:
    """CSV pivot for spreadsheet inspection."""
    df = df[df["state"] == "finished"].dropna(subset=[metric])
    pivot = df.pivot_table(
        values=metric,
        index=["method", "scenario"],
        columns="seed",
    )
    pivot["mean"] = pivot.mean(axis=1)
    pivot["std"] = pivot.std(axis=1)
    pivot.to_csv(output)
    print(f"Wrote {output}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", default="doccl-aaai2027")
    parser.add_argument("--entity", default=None)
    parser.add_argument("--output_dir", type=Path, default=Path("results"))
    parser.add_argument("--metrics", nargs="+", default=["AA", "BWT", "AF"])
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    print(f"Pulling runs from {args.project}...")
    df = pull_runs(args.project, args.entity)
    print(f"Got {len(df)} runs")
    df.to_csv(args.output_dir / "all_runs.csv", index=False)

    for metric in args.metrics:
        print(f"\n=== {metric} ===")
        agg = aggregate(df, metric=metric)
        print(agg.to_string(index=False))

        write_main_table(df, args.output_dir / f"table_main_{metric}.tex", metric=metric)
        write_pivot_csv(df, args.output_dir / f"pivot_{metric}.csv", metric=metric)


if __name__ == "__main__":
    main()
