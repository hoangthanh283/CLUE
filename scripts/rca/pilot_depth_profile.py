"""Review C1 (2026-11-11): Fisher-weighted displacement by depth bucket at the first task boundary,
per pilot condition, mean over seeds, reported WITH and WITHOUT the head. The Fisher weighting
favours the head by construction, so the encoder-only share is the informative part. Also prints
the mean BWT per condition over the valid seeds.

A run is DEAD (excluded everywhere, listed with the reason) when its final AA is below 1.0 or its
retention matrix is all zeros. Runs with a non-default task order (``*_ord210``) are their own group.

    uv run python scripts/rca/pilot_depth_profile.py [results/pilot]
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

DEAD_AA = 1.0  # final AA below this (0-100 scale) = dead run
ENC = ("input", "early", "mid", "late")


def dead_reason(d: dict) -> str | None:
    aa = d.get("cl_metrics", {}).get("AA")
    if aa is None or not aa >= DEAD_AA:
        return f"final AA {aa} < {DEAD_AA}"
    if not np.any(np.asarray(d.get("matrix", []), dtype=float)):
        return "retention matrix all zeros"
    return None


def main() -> None:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "results/pilot")
    disp, bwt, excluded = defaultdict(list), defaultdict(list), []
    for f in sorted(root.glob("c*_seed*.json")):
        d = json.loads(f.read_text())
        why = dead_reason(d)
        if why:
            excluded.append((f.name, why))
            continue
        group = re.sub(r"_seed\d+", "", f.stem)  # c4_full, c4_full_ord210, ...
        bwt[group].append((d["seed"], d["cl_metrics"]["BWT"]))
        recs = [r for r in d.get("displacement_records", []) if r["task_boundary"] == "0_to_1"]
        if recs:  # older pilot JSONs carry no displacement records
            disp[group].append([recs[0]["by_depth"].get(k, 0.0) for k in (*ENC, "head")])

    print(f"Excluded dead runs ({len(excluded)}):")
    for name, why in excluded:
        print(f"  {name:28s} {why}")

    print(
        f"\n{'condition':16s} n  head/max-encoder   encoder share (input/early/mid/late), "
        "head excluded"
    )
    for cond, rows in sorted(disp.items()):
        m = np.mean(rows, axis=0)
        enc = m[:4] / max(m[:4].sum(), 1e-30)
        print(
            f"{cond:16s} {len(rows)}  {m[4] / max(m[:4].max(), 1e-30):12.0f}x      "
            + " / ".join(f"{x:.2f}" for x in enc)
        )

    print(f"\n{'condition':16s} n  mean BWT   per-seed BWT")
    for cond, vals in sorted(bwt.items()):
        per = ", ".join(f"s{s}={v:.2f}" for s, v in vals)
        print(f"{cond:16s} {len(vals)}  {np.mean([v for _, v in vals]):8.2f}   {per}")
    write_tex(root, disp, bwt)


ROWS = (("LayoutLMv3", "c4_full"), ("\\quad text and layout", "c3_no_image"),
        ("\\quad image and layout", "c2_no_text"), ("\\quad text only", "c1_text"),
        ("LiLT", "cl_lilt"), ("BROS", "cr_bros"), ("BERT", "cb_bert"))  # fmt: skip
ENCODERS = ("c4_full", "cl_lilt", "cr_bros", "cb_bert")
DEPTHS = ("embeddings", "layer.0", "layer.6", "layer.11", "classifier")


def write_tex(root: Path, disp: dict, bwt: dict) -> None:
    """paper_cvpr/supp_drift.tex + drift_vals.tex (thesis Sec. 6.1): linear CKA by depth at the
    first boundary, the encoder share of the Fisher-weighted displacement, the head ratio and
    the forgetting, per condition, mean over the live runs."""
    cka = defaultdict(list)
    for f in sorted(root.glob("c*_seed*.json")):
        d = json.loads(f.read_text())
        if dead_reason(d) or "ord210" in f.stem:
            continue
        rec = next(r["cka"] for r in d["cka_records"] if r["task_boundary"] == "0_to_1")
        row = [next(v for k, v in rec.items() if k.endswith(s)) for s in DEPTHS]
        cka[d["condition"]].append(row)
    hdr = "% AUTO-GENERATED by scripts/rca/pilot_depth_profile.py -- do not edit.\n"
    t = hdr + "\\begin{tabular}{@{}lcccccccccccc@{}}\n\\toprule\n"
    t += (" & & \\multicolumn{5}{c}{Linear CKA} & \\multicolumn{4}{c}{Encoder share of "
          "displacement (\\%)} & & \\\\\n\\cmidrule(lr){3-7}\\cmidrule(lr){8-11}\n"
          "Encoder and inputs & Runs & Emb. & L1 & L7 & L12 & Head & Input & Early & Mid & Late "
          "& Head ratio & AF \\\\\n\\midrule\n")  # fmt: skip
    stat = {}
    for lab, c in ROWS:
        ck, m = np.mean(cka[c], axis=0), np.mean(disp[c], axis=0)
        enc, ratio = 100 * m[:4] / m[:4].sum(), m[4] / m[:4].max()
        af = -np.mean([v for _, v in bwt[c]])
        stat[c] = (ck, enc, ratio, af)
        t += (f"{lab} & {len(cka[c])} & " + " & ".join(f"{x:.2f}" for x in ck) + " & "
              + " & ".join(f"{x:.0f}" for x in enc) + f" & {ratio:.0f}$\\times$ & {af:.1f} \\\\\n")  # fmt: skip
        if c == "c1_text":
            t += "\\midrule\n"
    Path("paper_cvpr/supp_drift.tex").write_text(t + "\\bottomrule\n\\end{tabular}\n")
    e = [stat[c] for c in ENCODERS]
    lo, hi = (lambda xs: f"{np.floor(min(xs) * 100) / 100:.2f}"), (
        lambda xs: f"{np.ceil(max(xs) * 100) / 100:.2f}"
    )  # noqa: E731
    v = {
        "nDriftCkaEmbMin": lo([s[0][0] for s in e]),
        "nDriftCkaLastMin": lo([s[0][3] for s in e]), "nDriftCkaLastMax": hi([s[0][3] for s in e]),
        "nDriftCkaHeadMin": lo([s[0][4] for s in e]), "nDriftCkaHeadMax": hi([s[0][4] for s in e]),
        "nDriftHeadRatioMin": f"{np.floor(min(s[2] for s in e)):.0f}",
        "nDriftLateShareMax": f"{np.ceil(max(s[1][3] for s in e)):.0f}",
        "nDriftAfMin": f"{np.floor(min(s[3] for s in e) * 10) / 10:.1f}",
        "nDriftAfMax": f"{np.ceil(max(s[3] for s in e) * 10) / 10:.1f}",
        "nDriftTextOnlyRuns": str(len(cka["c1_text"])),
    }  # fmt: skip
    assert all(np.all(np.diff(s[0][:4]) < 0) for s in e), "CKA not monotone in depth"
    Path("paper_cvpr/drift_vals.tex").write_text(
        hdr + "".join(f"\\newcommand{{\\{k}}}{{{x}}}\n" for k, x in v.items())
    )


if __name__ == "__main__":
    main()
